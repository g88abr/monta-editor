-- 1) Tabela de perfis de usuário
create table if not exists public.profiles (
  id uuid references auth.users(id) primary key,
  nome text,
  handle text unique,
  avatar_url text,
  criado_em timestamptz default now()
);

-- 2) Tabela de posts da comunidade
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) not null,
  autor text not null,
  handle text not null,
  titulo text not null,
  conteudo text,
  categoria text default 'duvida',
  curtidas integer default 0,
  created_at timestamptz default now()
);

-- 3) Tabela de curtidas (para evitar curtir duas vezes)
create table if not exists public.post_likes (
  id bigint generated by default as identity primary key,
  post_id bigint references public.posts(id) on delete cascade,
  user_id uuid references auth.users(id) not null,
  created_at timestamptz default now(),
  unique (post_id, user_id)
);

-- 4) Habilitar segurança em nível de linha (RLS)
alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.post_likes enable row level security;

-- 5) Políticas — Profiles
create policy "profiles_leitura_publica" on public.profiles
  for select to anon, authenticated using (true);

create policy "profiles_insercao_proprio" on public.profiles
  for insert to authenticated with check (auth.uid() = id);

create policy "profiles_atualizacao_propria" on public.profiles
  for update to authenticated using (auth.uid() = id);

-- 6) Políticas — Posts
create policy "posts_leitura_publica" on public.posts
  for select to anon, authenticated using (true);

create policy "posts_insercao_autenticados" on public.posts
  for insert to authenticated with check (auth.uid() = user_id);

create policy "posts_atualizacao_dono" on public.posts
  for update to authenticated using (auth.uid() = user_id);

create policy "posts_delecao_dono" on public.posts
  for delete to authenticated using (auth.uid() = user_id);

-- 7) Políticas — Curtidas
create policy "likes_leitura_publica" on public.post_likes
  for select to anon, authenticated using (true);

create policy "likes_insercao_autenticados" on public.post_likes
  for insert to authenticated with check (auth.uid() = user_id);

create policy "likes_delecao_dono" on public.post_likes
  for delete to authenticated using (auth.uid() = user_id);

-- 8) Índices úteis
create index if not exists idx_posts_created_at on public.posts(created_at desc);
create index if not exists idx_posts_categoria on public.posts(categoria);
create index if not exists idx_posts_user_id on public.posts(user_id);
create index if not exists idx_post_likes_post_id on public.post_likes(post_id);
create index if not exists idx_post_likes_user_id on public.post_likes(user_id);

